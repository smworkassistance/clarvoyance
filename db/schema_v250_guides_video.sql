-- auto-pause: N distinct reporters across the guide's posts within 7 days
create or replace function public.guide_reports_trg() returns trigger language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
  select count(distinct user_id) into v_n from public.guide_reports where guide_id = new.guide_id and created_at > now() - interval '7 days';
  update public.guides set reports_open = v_n,
         status = case when v_n >= public._setting('guide_reports_pause_at', 3)::int and status = 'active' then 'paused' else status end
   where id = new.guide_id;
  return null;
end $$;
drop trigger if exists guide_reports_after on public.guide_reports;
create trigger guide_reports_after after insert on public.guide_reports for each row execute function public.guide_reports_trg();

