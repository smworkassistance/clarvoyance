-- called by the INVITEE once, after Google sign-in, with the handle from ?ref=
create or replace function public.referral_register(p_handle text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare v_me uuid := auth.uid(); v_inv uuid; v_h text := lower(btrim(coalesce(p_handle, '')));
begin
  if v_me is null then return jsonb_build_object('ok', false, 'reason', 'no_session'); end if;
  if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then return jsonb_build_object('ok', false, 'reason', 'anonymous'); end if;
  if v_h !~ '^[a-z0-9_.]{3,20}$' then return jsonb_build_object('ok', false, 'reason', 'bad_handle'); end if;
  select user_id into v_inv from public.social_profiles where handle = v_h;
  if v_inv is null then return jsonb_build_object('ok', false, 'reason', 'no_inviter'); end if;
  if v_inv = v_me then return jsonb_build_object('ok', false, 'reason', 'self'); end if;
  if exists (select 1 from public.referrals where invitee_id = v_me) then return jsonb_build_object('ok', false, 'reason', 'already'); end if;
  insert into public.referrals (inviter_id, invitee_id, inviter_handle) values (v_inv, v_me, v_h);
  return jsonb_build_object('ok', true);
end $$;
revoke all on function public.referral_register(text) from public, anon;
grant execute on function public.referral_register(text) to authenticated;

-- called by anyone on app open: pays what is owed to ME (as invitee and/or inviter) — once each — and returns the XP to add locally
create or replace function public.referral_claim() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_me uuid := auth.uid(); v_in_xp int := 0; v_out_xp int := 0; v_n int; v_room int; v_paid_month int;
  v_inviter_xp numeric := public._setting('referral_inviter_xp', 100);
  v_invitee_xp numeric := public._setting('referral_invitee_xp', 50);
  v_cap int := public._setting('referral_monthly_cap', 50)::int;
begin
  if v_me is null then return jsonb_build_object('xp', 0); end if;
  -- qualify my pending invitees' rows (server-side check of THEIR real engagement)
  update public.referrals r set status = 'qualified', qualified_at = now()
   where r.status = 'pending' and (r.inviter_id = v_me or r.invitee_id = v_me) and public._has_engaged_day(r.invitee_id);
  -- as invitee: welcome XP once, only after qualification
  update public.referrals set invitee_paid_at = now()
   where invitee_id = v_me and status = 'qualified' and invitee_paid_at is null;
  get diagnostics v_n = row_count;
  v_in_xp := v_n * v_invitee_xp::int;
  -- as inviter: 100 XP per newly qualified invitee, within the monthly cap
  select count(*) into v_paid_month from public.referrals
   where inviter_id = v_me and inviter_paid_at >= date_trunc('month', now());
  v_room := greatest(0, v_cap - v_paid_month);
  with due as (
    select id from public.referrals where inviter_id = v_me and status = 'qualified' and inviter_paid_at is null
    order by qualified_at limit v_room
  )
  update public.referrals r set inviter_paid_at = now() from due where r.id = due.id;
  get diagnostics v_n = row_count;
  v_out_xp := v_n * v_inviter_xp::int;
  return jsonb_build_object('xp', v_in_xp + v_out_xp, 'as_invitee', v_in_xp, 'as_inviter', v_out_xp);
end $$;
revoke all on function public.referral_claim() from public, anon;
grant execute on function public.referral_claim() to authenticated;

