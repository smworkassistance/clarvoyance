-- does this user have at least one day whose engagement score crossed the "engaged day" bar?
create or replace function public._has_engaged_day(p_uid uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (
    select 1 from public.user_daily_log d
    where d.user_id = p_uid and d.daily_score is not null
      and d.daily_score * 100 >= coalesce((select engaged_day_threshold_pct from public.engagement_settings limit 1), 60)
  )
$$;
